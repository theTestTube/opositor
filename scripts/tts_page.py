def paragraphs(text):
    """Turn the script into speakable paragraphs: strip markdown, one unit per block."""
    clean = []
    for block in re.split(r"\n\s*\n", text.strip()):
        block = re.sub(r"^\s{0,3}#{1,6}\s*", "", block, flags=re.M)
        block = re.sub(r"[*_`>]", "", block)
        block = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", block)
        block = re.sub(r"^\s*[-•*]\s*", "", block, flags=re.M)
        block = re.sub(r"\s+", " ", block).strip()
        if block:
            clean.append(block)
    return clean


def _escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_page(text, title, lang="en", labels=None):
    chunks = paragraphs(text)
    ui = dict(DEFAULT_UI)
    if labels:
        ui.update({k: str(v) for k, v in labels.items() if k in DEFAULT_UI})
    html = (PLANTILLA
            .replace("__TITLE__", _escape(title))
            .replace("__LANG__", _escape(lang))
            .replace("__PARAGRAPHS__", json.dumps(chunks, ensure_ascii=False).replace("</", "<\\/"))
            .replace("__UI_JSON__", json.dumps(ui, ensure_ascii=False).replace("</", "<\\/")))
    for key, value in ui.items():
        html = html.replace("__UI_" + key.upper() + "__", _escape(value))
    return html
