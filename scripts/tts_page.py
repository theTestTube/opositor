#!/usr/bin/env python3
"""Generate a self-contained listen page that uses the browser's voice (Web Speech API).

It does not export audio: `speechSynthesis` plays and writes no files. For MP3, use Piper
(`skills/speak-summary/scripts/tts.sh`). This module only builds the HTML.

CLI usage: `python3 scripts/opositor.py tts-page script.txt output.html`.
"""
